package cmdnodes

import "fmt"

func isNodesHelpRequest(args []string) bool {
	if len(args) == 0 {
		return false
	}
	for _, a := range args {
		if a == "--help" || a == "-h" || a == "help" {
			return true
		}
	}
	return false
}

