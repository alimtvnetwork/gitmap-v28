package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// maxEntriesPerPart caps the entries per generated part file so every
// emitted file stays under the repo's 300-line file cap (one entry per
// line plus a short header).
const maxEntriesPerPart = 250

const (
	outputFile  = "allcommands_generated.go"
	partFileFmt = "allcommands_generated_part%d.go"
	partFileGl  = "allcommands_generated_part*.go"
)

// writeOutput renders the generated Go source, splitting the entry list
// across part files so no single emitted file crosses the 300-line cap.
func writeOutput(values []string) error {
	parts := chunkValues(values, maxEntriesPerPart)

	if err := writeAssembler(len(parts)); err != nil {
		return err
	}

	for i, chunk := range parts {
		if err := writePart(i+1, len(parts), chunk); err != nil {
			return err
		}
	}

	return removeStaleParts(len(parts))
}

// chunkValues splits values into consecutive chunks of at most size entries.
func chunkValues(values []string, size int) [][]string {
	var out [][]string

	for i := 0; i < len(values); i += size {
		end := i + size
		if end > len(values) {
			end = len(values)
		}

		out = append(out, values[i:end])
	}

	return out
}

// writeAssembler renders allcommands_generated.go — the package clause plus
// the reassembled generatedCommands var. All entries live in the part files.
func writeAssembler(partCount int) error {
	var b strings.Builder

	b.WriteString("// Code generated by internal/gencommands; DO NOT EDIT.\n\n")
	b.WriteString("package completion\n\n")
	b.WriteString("// generatedCommands is the deduplicated, sorted list of every Cmd* string\n")
	b.WriteString("// constant value discovered in const blocks that opted into completion via\n")
	b.WriteString("// the `gitmap:cmd top-level` marker comment. AllCommands() unions this slice\n")
	b.WriteString("// with manualExtras so completion stays in sync with constants automatically.\n")
	b.WriteString("//\n")
	b.WriteString("// Entries are split across allcommands_generated_partN.go (one part per\n")
	b.WriteString("// <=250 entries) to honor the repo's 300-line file cap; this file only\n")
	b.WriteString("// reassembles the parts in order.\n")
	b.WriteString("var generatedCommands = assembleGeneratedCommands()\n\n")
	b.WriteString("// assembleGeneratedCommands concatenates the per-part generated slices.\n")
	b.WriteString("func assembleGeneratedCommands() []string {\n")
	b.WriteString("\tvar out []string\n")

	for i := 1; i <= partCount; i++ {
		fmt.Fprintf(&b, "\tout = append(out, generatedCommandsPart%d...)\n", i)
	}

	b.WriteString("\treturn out\n")
	b.WriteString("}\n")

	return os.WriteFile(outputFile, []byte(b.String()), 0o644)
}

// writePart renders one allcommands_generated_partN.go chunk file.
func writePart(index, total int, chunk []string) error {
	var b strings.Builder

	b.WriteString("// Code generated by internal/gencommands; DO NOT EDIT.\n\n")
	b.WriteString("package completion\n\n")
	fmt.Fprintf(&b, "// generatedCommandsPart%d holds chunk %d of %d of the generated command\n", index, index, total)
	b.WriteString("// list (see allcommands_generated.go).\n")
	fmt.Fprintf(&b, "var generatedCommandsPart%d = []string{\n", index)

	for _, v := range chunk {
		fmt.Fprintf(&b, "\t%q,\n", v)
	}

	b.WriteString("}\n")

	return os.WriteFile(fmt.Sprintf(partFileFmt, index), []byte(b.String()), 0o644)
}

// removeStaleParts deletes part files left over from a previous run that
// emitted more parts (e.g. after commands were removed). Without this the
// drift check would stay green while stale entries lingered in the build.
func removeStaleParts(partCount int) error {
	matches, err := filepath.Glob(partFileGl)
	if err != nil {
		return fmt.Errorf("glob part files: %w", err)
	}

	for _, m := range matches {
		var index int
		if _, err := fmt.Sscanf(filepath.Base(m), partFileFmt, &index); err != nil {
			continue
		}

		if index <= partCount {
			continue
		}

		if err := os.Remove(m); err != nil {
			return fmt.Errorf("remove stale part file %s: %w", m, err)
		}
	}

	return nil
}
