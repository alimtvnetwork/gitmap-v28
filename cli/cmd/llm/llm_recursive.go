package llm

import "strings"

// RenderRecursiveInstructions returns recursive Git network learning directives.
func RenderRecursiveInstructions() string {
	var b strings.Builder

	b.WriteString("======================================================================\n")
	b.WriteString("STAGE 4: RECURSIVE GIT NETWORK LEARNING DIRECTIVES\n")
	b.WriteString("======================================================================\n")
	b.WriteString("1. Multi-Repository Network Discovery:\n")
	b.WriteString("   - AI agents must scan and track multi-repo workspaces using 'gitmap st', 'gitmap commit-in', and 'gitmap commit-pull'.\n")
	b.WriteString("   - Understand network dependencies across polyglot repositories before applying cross-cutting changes.\n\n")
	b.WriteString("2. Telemetry Recursion & Prior Mistake Prevention:\n")
	b.WriteString("   - Always run 'gitmap pe history-ai [N]' to inspect recent CI failure patterns before modifying code.\n")
	b.WriteString("   - Ensure new changes avoid regressions documented in .ai-memory/pipeline-ai/ dossiers.\n\n")
	b.WriteString("3. Non-Blocking CI Telemetry Loop:\n")
	b.WriteString("   - Use 'gitmap pe -t --ai' for dynamic wait calculations instead of CPU-spinning poll loops.\n")
	b.WriteString("   - Use '-ud' / '--until-done' to monitor the entire pipeline run through final status.\n\n")
	b.WriteString("4. Persistent Memory Ledger Synchronization:\n")
	b.WriteString("   - After completing tasks, record decisions into .ai-memory/what-to-read.md and task plans.\n")
	b.WriteString("   - Keep workspace knowledge synchronized across all AI sessions.\n")

	return b.String()
}

