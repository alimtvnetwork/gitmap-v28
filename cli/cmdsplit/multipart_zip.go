package cmdsplit

import (
	"archive/zip"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/alimtvnetwork/gitmap-v28/cli/apperror"
)

// MultipartSplitResult holds the details of a file split operation.
type MultipartSplitResult struct {
	SourcePath        string
	OriginalSize      int64
	ChunkSize         int64
	CompressionMethod uint16
	ChunkFiles        []string
}

// chunkedZipWriter splits written data into multipart chunks across .zip, .z01, .z02...
type chunkedZipWriter struct {
	basePath           string
	chunkSize          int64
	currentPart        int
	currentFile        *os.File
	bytesInCurrentPart int64
	allPartPaths       []string
}

// formatPartName returns the filename for a given chunk index.
func formatPartName(basePath string, partIndex int) string {
	if partIndex == 0 {
		return basePath + ".zip"
	}

	return fmt.Sprintf("%s.z%02d", basePath, partIndex)
}

// IsPrecompressedMedia returns true for media files that should not be recompressed.
func IsPrecompressedMedia(filename string) bool {
	ext := strings.ToLower(filepath.Ext(filename))

	switch ext {
	case ".png", ".jpg", ".jpeg", ".webp", ".mp4", ".mov", ".mkv", ".mp3", ".wav", ".aac", ".m4a":
		return true
	default:
		return false
	}
}

// ResolveCompressionMethod returns zip.Store for pre-compressed media or zip.Deflate otherwise.
func ResolveCompressionMethod(filename string) uint16 {
	if IsPrecompressedMedia(filename) {
		return zip.Store
	}

	return zip.Deflate
}

// CompressionMethodName returns a human-readable name for the compression method.
func CompressionMethodName(method uint16) string {
	if method == zip.Store {
		return "STORE"
	}

	return "DEFLATE"
}

// newChunkedZipWriter initializes a chunked zip writer.
func newChunkedZipWriter(basePath string, chunkSize int64) *chunkedZipWriter {
	return &chunkedZipWriter{
		basePath:     basePath,
		chunkSize:    chunkSize,
		currentPart:  0,
		allPartPaths: make([]string, 0),
	}
}

func (w *chunkedZipWriter) openNextPart() error {
	partName := formatPartName(w.basePath, w.currentPart)
	w.currentPart++

	f, err := os.OpenFile(partName, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o644)
	if err != nil {
		return apperror.WrapSimple(err, "chunked_zip.open_part")
	}

	w.currentFile = f
	w.bytesInCurrentPart = 0
	w.allPartPaths = append(w.allPartPaths, partName)

	return nil
}

func (w *chunkedZipWriter) closeCurrentPart() error {
	if w.currentFile == nil {
		return nil
	}

	err := w.currentFile.Close()
	w.currentFile = nil

	if err != nil {
		return apperror.WrapSimple(err, "chunked_zip.close_part")
	}

	return nil
}

func (w *chunkedZipWriter) ensureActivePart() error {
	isAvailable := w.currentFile != nil && w.bytesInCurrentPart < w.chunkSize
	if isAvailable {
		return nil
	}

	if err := w.closeCurrentPart(); err != nil {
		return err
	}

	return w.openNextPart()
}

func (w *chunkedZipWriter) writeChunkSlice(p []byte) (int, error) {
	if err := w.ensureActivePart(); err != nil {
		return 0, err
	}

	available := w.chunkSize - w.bytesInCurrentPart
	toWrite := len(p)
	if int64(toWrite) > available {
		toWrite = int(available)
	}

	n, err := w.currentFile.Write(p[:toWrite])
	w.bytesInCurrentPart += int64(n)

	return n, err
}

// Write writes bytes into chunked files, rolling over when chunkSize is reached.
func (w *chunkedZipWriter) Write(p []byte) (int, error) {
	totalWritten := 0

	for len(p) > 0 {
		n, err := w.writeChunkSlice(p)
		totalWritten += n
		if err != nil {
			return totalWritten, err
		}

		p = p[n:]
	}

	return totalWritten, nil
}

// Close closes the active chunk file.
func (w *chunkedZipWriter) Close() error {
	return w.closeCurrentPart()
}

// PartPaths returns all paths generated by this writer.
func (w *chunkedZipWriter) PartPaths() []string {
	return w.allPartPaths
}

// CreateMultipartZip splits a single file into multipart zip chunks.
func CreateMultipartZip(sourcePath string, chunkSize int64) (*MultipartSplitResult, error) {
	fi, err := os.Stat(sourcePath)
	if err != nil {
		return nil, apperror.WrapSimple(err, "stat_source_file")
	}

	method := ResolveCompressionMethod(sourcePath)
	cw := newChunkedZipWriter(sourcePath, chunkSize)

	if err := writeSourceToArchive(sourcePath, fi, method, cw); err != nil {
		cw.Close()
		return nil, err
	}

	return buildSplitResult(sourcePath, fi.Size(), chunkSize, method, cw.PartPaths()), nil
}

func writeSourceToArchive(sourcePath string, fi os.FileInfo, method uint16, cw *chunkedZipWriter) error {
	zw := zip.NewWriter(cw)

	if err := copyFileEntryToZip(sourcePath, fi, method, zw); err != nil {
		zw.Close()
		return err
	}

	if err := zw.Close(); err != nil {
		return apperror.WrapSimple(err, "zip_close")
	}

	return cw.Close()
}

func copyFileEntryToZip(sourcePath string, fi os.FileInfo, method uint16, zw *zip.Writer) error {
	header := &zip.FileHeader{
		Name:     filepath.Base(sourcePath),
		Method:   method,
		Modified: fi.ModTime(),
	}

	entryWriter, err := zw.CreateHeader(header)
	if err != nil {
		return apperror.WrapSimple(err, "create_zip_header")
	}

	return streamFileContent(sourcePath, entryWriter)
}

func streamFileContent(sourcePath string, dest io.Writer) error {
	srcFile, err := os.Open(sourcePath)
	if err != nil {
		return apperror.WrapSimple(err, "open_source_file")
	}
	defer srcFile.Close()

	_, err = io.Copy(dest, srcFile)
	if err != nil {
		return apperror.WrapSimple(err, "copy_to_zip")
	}

	return nil
}

func buildSplitResult(path string, origSize, chunkSize int64, method uint16, parts []string) *MultipartSplitResult {
	return &MultipartSplitResult{
		SourcePath:        path,
		OriginalSize:      origSize,
		ChunkSize:         chunkSize,
		CompressionMethod: method,
		ChunkFiles:        parts,
	}
}

// ReassembleMultipartZip combines .zip and .zXX chunks into a single zip archive.
func ReassembleMultipartZip(firstPartPath string, destZipPath string) error {
	parts := discoverPartSequence(firstPartPath)
	if len(parts) == 0 {
		return apperror.NewNotFound("reassemble", "E404", "no multipart parts found")
	}

	outFile, err := os.Create(destZipPath)
	if err != nil {
		return apperror.WrapSimple(err, "create_dest_zip")
	}
	defer outFile.Close()

	return concatenateParts(parts, outFile)
}

func discoverPartSequence(firstPart string) []string {
	base := strings.TrimSuffix(firstPart, ".zip")
	parts := []string{firstPart}

	for idx := 1; ; idx++ {
		nextPart := fmt.Sprintf("%s.z%02d", base, idx)
		if _, err := os.Stat(nextPart); err != nil {
			break
		}

		parts = append(parts, nextPart)
	}

	return parts
}

func concatenateParts(parts []string, dest io.Writer) error {
	for _, part := range parts {
		if err := copyPartFile(part, dest); err != nil {
			return err
		}
	}

	return nil
}

func copyPartFile(partPath string, dest io.Writer) error {
	f, err := os.Open(partPath)
	if err != nil {
		return apperror.WrapSimple(err, "open_part_file")
	}
	defer f.Close()

	_, err = io.Copy(dest, f)
	if err != nil {
		return apperror.WrapSimple(err, "copy_part_file")
	}

	return nil
}
