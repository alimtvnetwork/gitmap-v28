package main

import (
	"fmt"
	"os"
	"strings"
)

// resolvedEntry is one catalog row after merging the dispatcher
// registration with the curated annotation.
type resolvedEntry struct {
	name        string
	alias       string
	version     string
	category    string
	description string
	example     string
}

// emitCatalog merges annotations with the registry and writes the
// generated Go catalog. Alias resolution rules:
//
//   - multi-word names ("te all", "sync --dry-run") keep the annotated
//     alias: the registration only knows the base command.
//   - single-word names take the alias from the registration (first
//     registered name that is not the base), so the catalog cannot drift
//     from the real CLI surface.
//   - when the base command has no registration, the annotated alias is
//     kept and the entry is reported on stderr (informational only).
func emitCatalog(path string, anns []annotation, reg registry) error {
	var b strings.Builder

	b.WriteString("// Code generated by ncgen; DO NOT EDIT.\n\n")
	b.WriteString("package cmdpending\n\n")
	b.WriteString("// generatedCatalogEntries is the new-commands catalog produced at\n")
	b.WriteString("// build time by cli/cmdpending/ncgen: command names and aliases come\n")
	b.WriteString("// from the dispatcher registration (cli/cmd dispatch tables and cobra\n")
	b.WriteString("// commands); descriptions, examples, versions, and categories are\n")
	b.WriteString("// curated in cli/cmdpending/ncgen/nc_annotations.json. Regenerate\n")
	b.WriteString("// with: go generate ./cli/cmdpending/\n")
	b.WriteString("func generatedCatalogEntries() []NewCommandEntry {\n")
	b.WriteString("\treturn []NewCommandEntry{\n")

	unregistered := []string{}

	for _, a := range anns {
		e := resolveEntry(a, reg, &unregistered)
		fmt.Fprintf(&b, "\t\t{Name: %q, Alias: %q, Version: %q, Category: %q, Description: %q, Example: %q},\n",
			e.name, e.alias, e.version, e.category, e.description, e.example)
	}

	b.WriteString("\t}\n}\n")

	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}

	fmt.Fprintf(os.Stderr, "ncgen: wrote %d entries to %s", len(anns), path)
	if len(unregistered) > 0 {
		fmt.Fprintf(os.Stderr, " (%d without dispatcher registration: %s)",
			len(unregistered), strings.Join(unregistered, ", "))
	}

	fmt.Fprintln(os.Stderr)

	return nil
}

func resolveEntry(a annotation, reg registry, unregistered *[]string) resolvedEntry {
	e := resolvedEntry{
		name:        a.Name,
		alias:       a.Alias,
		version:     a.Version,
		category:    a.Category,
		description: a.Description,
		example:     a.Example,
	}

	// Multi-word forms keep the editorial alias; the registration only
	// knows the base command.
	if strings.Contains(a.Name, " ") {
		return e
	}

	rc := reg[a.Name]
	if rc == nil {
		*unregistered = append(*unregistered, a.Name)
		return e
	}

	e.alias = firstAlias(rc.names, a.Name)

	if e.description == "" {
		e.description = rc.short
	}

	return e
}

// firstAlias returns the first registered name that is not the base
// command itself, or "" when the command has no aliases.
func firstAlias(names []string, base string) string {
	for _, n := range names {
		if n != base {
			return n
		}
	}

	return ""
}
